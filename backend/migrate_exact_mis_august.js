function runQuery(sql, params = []) {
  return new Promise((resolve, reject) => {
    db.run(sql, params, function(err) {
      if (err) return reject(err);
      resolve(this);
    });
  });
}

function getRows(sql, params = []) {
  return new Promise((resolve, reject) => {
    db.all(sql, params, (err, rows) => {
      if (err) return reject(err);
      resolve(rows);
    });
  });
}

async function migrate() {
  console.log('1. Checking and adding missing columns to project_deliverables in unified_sanna_crm.db...');
  
  const columnsToAdd = [
    { name: 'type', type: 'TEXT DEFAULT "Non-DM"' },
    { name: 'follower_gain', type: 'TEXT DEFAULT ""' },
    { name: 'view_gain', type: 'TEXT DEFAULT ""' },
    { name: 'keywords_injected', type: 'INTEGER DEFAULT 0' },
    { name: 'gmb_position', type: 'TEXT DEFAULT ""' },
    { name: 'amount_spend_ads', type: 'REAL DEFAULT 0' },
    { name: 'total_leads_generated', type: 'INTEGER DEFAULT 0' },
    { name: 'lead_ticket_size', type: 'REAL DEFAULT 0' },
    { name: 'achievement', type: 'TEXT DEFAULT ""' }
  ];

  const cols = await getRows('PRAGMA table_info(project_deliverables)');
  const existingColNames = new Set(cols.map(c => c.name));

  for (const col of columnsToAdd) {
    if (!existingColNames.has(col.name)) {
      try {
        await runQuery(`ALTER TABLE project_deliverables ADD COLUMN ${col.name} ${col.type}`);
        console.log(`+ Added column ${col.name}`);
      } catch (e) {
        console.warn(`Column ${col.name} note:`, e.message);
      }
    }
  }

  console.log('2. Deleting only August (month = 8, year = 2026) deliverables...');
  await runQuery('DELETE FROM project_deliverables WHERE month = 8 AND year = 2026');

  console.log('3. Inserting exact 20 August rows matching MIS...');
  for (const d of EXACT_MIS_AUGUST_ROWS) {
    await runQuery(`INSERT INTO project_deliverables (
      project_id, project_name, type, service, month, year, delivery_date,
      reels_planned, posts_planned, reels_delivered, posts_delivered,
      total_followers, follower_gain, views_reached, view_gain,
      backlinks_created, keywords_injected, gmb_position, amount_spend_ads,
      total_leads_generated, lead_ticket_size, achievement,
      approval_pending_remarks, other_remarks
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`, [
      d.project_id, d.project_name, d.type, d.service, d.month, d.year, d.delivery_date,
      d.reels_planned, d.posts_planned, d.reels_delivered, d.posts_delivered,
      d.total_followers, d.follower_gain, d.views_reached, d.view_gain,
      d.backlinks_created, d.keywords_injected, d.gmb_position, d.amount_spend_ads,
      d.total_leads_generated, d.lead_ticket_size, d.achievement,
      d.approval_pending_remarks, d.other_remarks
    ]);
  }

  console.log('4. Syncing src/data/realCrmData.js with updated database...');
  const allRows = await getRows('SELECT * FROM project_deliverables ORDER BY month ASC, id ASC');

  const realDataPath = path.join(__dirname, '..', 'src', 'data', 'realCrmData.js');
  let content = fs.readFileSync(realDataPath, 'utf8');

  const mappedDeliverables = allRows.map(r => ({
    id: String(r.id),
    projectId: `deal-${r.project_id || r.id}`,
    projectName: r.project_name || '',
    clientName: r.project_name || '',
    type: r.type || 'Non-DM',
    month: r.month,
    year: r.year,
    deliveryDate: r.delivery_date || '',
    reelsPlanned: r.reels_planned || 0,
    reelsDelivered: r.reels_delivered || 0,
    postsPlanned: r.posts_planned || 0,
    postsDelivered: r.posts_delivered || 0,
    service: r.service || 'Social Media Management',
    totalFollowers: r.total_followers || '',
    followerGain: r.follower_gain || '',
    viewsReached: r.views_reached || '',
    viewGain: r.view_gain || '',
    backlinksCreated: parseInt(r.backlinks_created, 10) || 0,
    keywordsInjected: parseInt(r.keywords_injected, 10) || 0,
    gmbPosition: r.gmb_position || '',
    adsSpend: r.amount_spend_ads ? String(r.amount_spend_ads) : '',
    leads: r.total_leads_generated ? String(r.total_leads_generated) : '',
    leadTicketSize: r.lead_ticket_size ? String(r.lead_ticket_size) : '',
    achievement: r.achievement || '',
    approvalPendingRemarks: r.approval_pending_remarks || '',
    otherRemarks: r.other_remarks || '',
    remarks: r.approval_pending_remarks || r.other_remarks || ''
  }));

  const startIdx = content.indexOf('"deliverables": [');
  if (startIdx !== -1) {
    let endIdx = content.indexOf('],', startIdx);
    if (endIdx === -1) endIdx = content.indexOf(']', startIdx);
    const replacement = `"deliverables": ${JSON.stringify(mappedDeliverables, null, 2)}`;
    content = content.slice(0, startIdx) + replacement + content.slice(endIdx + 1);
    fs.writeFileSync(realDataPath, content, 'utf8');
    console.log(`✅ [SUCCESS] Synced ${mappedDeliverables.length} total deliverables (including 20 August rows) to realCrmData.js!`);
  }

  db.close();
}

migrate().catch(console.error);
